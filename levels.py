"""关卡数据。

用「网格坐标」而不是手写 ASCII 来定义，好处是不会因为数错空格而错位。

跳跃能力预算（用于设计关卡时的间距上限）：
    跑速 118 px/s，起跳初速 -232 px/s，重力 900 px/s²
    -> 单跳高度约 30 px（2 格），单跳水平距离约 56 px（3.5 格）
    -> 二段跳总高度约 86 px（5 格），总水平距离约 110 px（7 格）
所以：平地间距 <= 3 格最舒服，<= 6 格必须二段跳；升高 <= 2 格可单跳，
      <= 4 格需要二段跳。下面所有平台都按这个预算摆放。

图例（最终网格里使用的字符）
  #  草地方块      .  泥土          %  石砖          B  红砖
  W  木板          C  木箱          M  铁块          =  移动平台
  ~  云朵平台      L  梯子          T  装饰（树 / 火把）
  ^  尖刺          V  冰晶
  ?  金币砖        x  用过的砖
  P  出生点        G  终点门
  o  金币          *  宝石          h  回血爱心
  s  史莱姆        b  蝙蝠          w  刺壳虫
  j  弹簧
"""
from __future__ import annotations

from dataclasses import dataclass


class Canvas:
    """按行列坐标绘制关卡网格。"""

    def __init__(self) -> None:
        self.rows: dict[int, dict[int, str]] = {}

    # -- 基础写入 --------------------------------------------------------
    def put(self, x: int, y: int, ch: str) -> None:
        self.rows.setdefault(y, {})[x] = ch

    def many(self, coords, ch: str) -> None:
        for x, y in coords:
            self.put(x, y, ch)

    def rect(self, x0: int, y0: int, x1: int, y1: int, ch: str) -> None:
        """闭区间填充。# 的顶行自动变成草地，下面自动变成泥土。"""
        for y in range(y0, y1 + 1):
            for x in range(x0, x1 + 1):
                if ch == "#" and y != y0:
                    self.put(x, y, ".")
                else:
                    self.put(x, y, ch)

    def plat(self, x0: int, x1: int, y: int, ch: str = "B") -> None:
        for x in range(x0, x1 + 1):
            self.put(x, y, ch)

    def coins(self, x0: int, x1: int, y: int, coin: str = "o") -> None:
        for x in range(x0, x1 + 1):
            self.put(x, y, coin)

    def coin_blocks(self, coords, y: int) -> None:
        for x in coords:
            self.put(x, y, "?")

    # -- 输出 ------------------------------------------------------------
    def build(self) -> list[str]:
        if not self.rows:
            return []
        max_y = max(self.rows)
        max_x = max(max(r) for r in self.rows.values())
        out: list[str] = []
        for y in range(max_y + 1):
            line = [" "] * (max_x + 1)
            for x, ch in self.rows.get(y, {}).items():
                line[x] = ch
            out.append("".join(line))
        return out

    def preview(self) -> str:
        return "\n".join(self.build())


