@dataclass
class LevelDef:
    name: str
    subtitle: str
    theme: str
    music: str
    rows: list[str]
    par_time: float = 60.0


LEVELS: list[LevelDef] = [
    LevelDef(name="晨光草原", subtitle="Dawn Meadow", theme="dawn", music="adventure",
             rows=_level1(), par_time=75.0),
    LevelDef(name="幽暗洞窟", subtitle="Gloom Cavern", theme="cave", music="calm",
             rows=_level2(), par_time=120.0),
    LevelDef(name="夜空高塔", subtitle="Night Tower", theme="night", music="adventure",
             rows=_level3(), par_time=150.0),
]


def level_count() -> int:
    return len(LEVELS)
