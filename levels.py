def _level3() -> list[str]:
    c = Canvas()
    W = 130

    # ── 底部深渊 ────────────────────────────────────────────────────
    c.plat(0, W - 1, 29, "^")
    c.plat(0, W - 1, 2, "B")            # 顶部装饰横梁（够不到，纯视觉）

    # ── 主平台（在第 25~28 行），中间挖出三个「天井」用来上升 ────────
    shafts = [(22, 25), (60, 63), (100, 103)]
    for x0, x1 in shafts:
        c.rect(0, 25, x0 - 1, 28, "#")
        c.rect(x1 + 1, 25, W - 1, 28, "#")
    # 天井两侧的石壁（防止从侧面掉进深渊）
    for x0, x1 in shafts:
        c.rect(x0, 27, x1, 28, "#")

    # 平台表面的装饰木箱（不挡路）
    for x in range(3, W - 3, 11):
        if any(x0 <= x <= x1 for x0, x1 in shafts):
            continue
        c.put(x, 24, "C")

    # ── 天井里的移动平台（上升气流）────────────────────────────────
    for x0, x1 in shafts:
        c.plat(x0 - 1, x1 + 1, 21, "=")

    # ── 第二层：云朵平台（间距 3~4 格）──────────────────────────────
    c.plat(14, 27, 17, "~")
    c.plat(31, 44, 17, "~")
    c.plat(48, 61, 17, "~")
    c.plat(65, 78, 17, "~")
    c.plat(82, 95, 17, "~")
    c.plat(99, 112, 17, "~")

    # ── 第三层：红砖平台 ────────────────────────────────────────────
