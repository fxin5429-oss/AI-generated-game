    c.plat(44, 52, 6, "W")
    c.plat(70, 78, 6, "W")
    c.plat(96, 104, 6, "W")

    # ── 塔身（从主平台往上跳的中转点）──────────────────────────────
    towers = [(34, 41), (72, 79), (110, 117)]
    for x0, x1 in towers:
        c.rect(x0, 19, x1, 24, "#")
        c.plat(x0, x1, 18, "B")

    # ── 金币砖 ──────────────────────────────────────────────────────
    c.coin_blocks([8, 10, 12], 11)
    c.coin_blocks([28, 30, 32], 11)
    c.coin_blocks([54, 56, 58], 11)
    c.coin_blocks([80, 82, 84], 11)
    c.coin_blocks([106, 108, 110], 11)
    c.coin_blocks([20, 22, 24], 5)
    c.coin_blocks([46, 48, 50], 5)
    c.coin_blocks([72, 74, 76], 5)
    c.coin_blocks([98, 100, 102], 5)

    # ── 弹簧（放在没有天井的地方）──────────────────────────────────
    c.put(17, 24, "j")
    c.put(65, 24, "j")
    c.put(115, 24, "j")

    # ── 尖刺 & 冰晶 ─────────────────────────────────────────────────
    c.plat(30, 33, 11, "^")
    c.plat(56, 59, 11, "^")
    c.plat(82, 85, 11, "^")
    c.many([(24, 16), (45, 16), (58, 16), (76, 16), (92, 16), (10, 11), (50, 11), (108, 11)], "V")

    # ── 金币 ────────────────────────────────────────────────────────
